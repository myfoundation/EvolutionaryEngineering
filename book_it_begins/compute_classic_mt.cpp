#define LOG printf

//------------------------------------------
// CLASSIC TURING MACHINE 1936
//------------------------------------------
enum Action
{
    MVL, // Шаг влево
    MVR, // Шаг вправо
    HLT  // Маркер финального состояния (Аппаратный останов)
};

// СТРОКА FSM ТАБЛИЦЫ
struct FSM_entry
{
    int
        current_state,  // ТЕКУЩЕЕ СОСТОЯНИЕ REG_STATE
        in_symbol,      // ВХОДЯЩИЙ СИМВОЛ
        next_state,     // СЛЕДУЮЩЕЕ СОСТОЯНИЕ
        out_symbol,     // ИСХОДЯЩИЙ СИМВОЛ
        action          // СИГНАЛ АППАРАТУРЕ
   ;
};

struct UMT_context
{
    //------------------------------------------
    // EXECUTION CONTEXT
    //------------------------------------------
    int
        // РЕГИСТРЫ МАШИНЫ
        REG_STATE,     // Текущее состояние машины из FSM таблицы
        REG_HEAD_POS,  // Указатель на выбранную ячейку RAM
        // ПАМЯТЬ С ДАННЫМИ
        *RAM           // Вставка "ленты" меняет пространство состояний автомата
    ;
    //------------------------------------------

    //------------------------------------------
    // FSM TABLE
    //------------------------------------------
    FSM_entry *FSM_TABLE;
    int FSM_SIZE;
    //------------------------------------------
};

void UMT_run(UMT_context *CTX)
{
    int is_run = 1;
    while (is_run)
    {
        FSM_entry* step = NULL;

// 1. СЧИТАТЬ СИМВОЛ I_вх С ЛЕНТЫ
        int IN = CTX->RAM[CTX->REG_HEAD_POS];

// 2. ПО ПАРЕ { S_тек, I_вх} НАЙТИ СООТВЕТСТВУЮЩУЮ СТРОКУ В FSM_TABLE
        // Аппаратный поиск кортежа дельта-функции на перфоленте
        for (int i = 0; i < CTX->FSM_SIZE; ++i)
        {
            if ( CTX->FSM_TABLE[i].current_state == CTX->REG_STATE &&
                 CTX->FSM_TABLE[i].in_symbol == IN )
            {
                step = &CTX->FSM_TABLE[i];
                break;
            }
        }

        if(!step)
        {
            LOG("ERR: INTERNAL LOGIC ERROR. UNEXPECTED SYMBOL %d IN STATE %d\n", IN, CTX->REG_STATE);
            return;
        }

// 3. ЗАПИСАТЬ СИМВОЛ I_вых НА ЛЕНТУ
        CTX->RAM[CTX->REG_HEAD_POS] = step->out_symbol;
// 4. ИЗМЕНИТЬ НОМЕР СОСТОЯНИЯ НА S_но.
        CTX->REG_STATE = step->next_state;

// 5. СДВИНУТЬ ПОЗИЦИЮ ГОЛОВКИ СООТВЕТСТВЕННО Action
        switch(step->action)
        {
            case MVL: CTX->REG_HEAD_POS--; break;
            case MVR: CTX->REG_HEAD_POS++; break;
            case HLT: is_run = 0; break;
        }
    }
}
